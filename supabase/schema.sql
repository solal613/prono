create table if not exists public.matches (
  id bigint generated by default as identity primary key,
  sport text not null default 'football',
  team_a text not null,
  team_b text not null,
  date date not null,
  time text not null default '18:00',
  status text not null default 'À venir',
  score_a integer null,
  score_b integer null,
  odds_1 numeric null,
  odds_n numeric null,
  odds_2 numeric null,
  created_at timestamp with time zone default now()
);

create table if not exists public.bets (
  id bigint generated by default as identity primary key,
  user_id text not null default 'guest',
  match_id bigint references public.matches(id) on delete cascade,
  choice text not null,
  amount integer not null default 10,
  status text not null default 'pending',
  created_at timestamp with time zone default now()
);

create index if not exists idx_matches_date on public.matches(date);
create index if not exists idx_bets_user on public.bets(user_id);

alter table public.matches enable row level security;
alter table public.bets enable row level security;

create policy "Public can read matches" on public.matches for select using (true);
create policy "Public can insert bets" on public.bets for insert with check (true);
create policy "Public can read bets" on public.bets for select using (true);
